import { expect, test } from "vitest";
import {
  anthropic, dayState, doneRecord, errorRecord, noProvider, ollama, silentView, view,
} from "./insights.fixtures";
import { ApiError, JobError } from "./api";
import {
  followUpHref, generatedLine, generateSentence, money, NO_SPEECH, pollError, rangeEstimate, rangeResult, tabState,
  VANISHED,
} from "./insights";

test("no provider configured comes first, unless the day already has its insight", () => {
  expect(tabState(dayState(), noProvider, view)).toBe("no-provider");
  expect(tabState(dayState({ state: "error", record: errorRecord }), noProvider, view)).toBe("no-provider");
  expect(tabState(dayState({ reason: "No model chosen." }), ollama, view)).toBe("no-provider");
  // a done record is shown whatever the provider setting
  expect(tabState(dayState({ state: "done", record: doneRecord }), noProvider, view)).toBe("done");
  expect(tabState(dayState({ state: "done", record: doneRecord, reason: "No model chosen." }), ollama, view)).toBe("done");
});

test("a day without a conversation with lines has nothing to summarise", () => {
  expect(tabState(dayState(), ollama, silentView)).toBe("no-speech");
  expect(tabState(dayState({ reason: NO_SPEECH }), ollama, view)).toBe("no-speech");
});

test("none, generating, error and done follow the server's state", () => {
  expect(tabState(dayState(), ollama, view)).toBe("none");
  expect(tabState(dayState({ state: "generating", job: "j1" }), ollama, view)).toBe("generating");
  expect(tabState(dayState({ state: "error", record: errorRecord }), ollama, view)).toBe("error");
  expect(tabState(dayState({ state: "done", record: doneRecord }), ollama, view)).toBe("done");
});

test("a reason Generate is refused makes the day unusable, but a done insight is still shown", () => {
  const reason = "No key saved. Add one in Settings › Model.";
  expect(tabState(dayState({ reason }), anthropic, view)).toBe("unusable");
  expect(tabState(dayState({ state: "error", record: errorRecord, reason }), anthropic, view)).toBe("unusable");
  expect(tabState(dayState({ state: "done", record: doneRecord, reason }), anthropic, view)).toBe("done");
});

test("the Generate sentence names a cloud provider and says a local one stays on this Mac", () => {
  expect(generateSentence(anthropic)).toBe("Sends this day's transcript text to Anthropic.");
  expect(generateSentence(ollama)).toBe("Runs on this Mac.");
});

test("a follow-up with a line links to it; one without has no link", () => {
  const [linked, plain] = doneRecord.insight!.follow_ups;
  expect(followUpHref("2026-10-23", linked)).toBe("#/day/2026-10-23?at=clip_b-0");
  expect(followUpHref("2026-10-23", plain)).toBeNull();
  expect(followUpHref("2026-10-23", { text: "x", at_ms: null, line_id: "a b&c" })).toBe("#/day/2026-10-23?at=a+b%26c");
});

test("the generated line names the model and the time, and says when the day was cut", () => {
  expect(generatedLine(doneRecord)).toBe("Generated by qwen3:8b at 23:05");
  expect(generatedLine({ ...doneRecord, truncated: true }))
    .toBe("Generated by qwen3:8b at 23:05 (the earlier part of the day was left out)");
});

const opus = {
  ...anthropic, model: "claude-opus-5-5",
  facts: { sends: "each day's transcript text and your questions, never audio", to: "Anthropic",
    cost: "about $0.20 per 3-hour day" },
  models: [
    { id: "claude-opus-5-5", label: "Claude Opus 5.5", recommended: true, cost_per_day: "about $0.20 per 3-hour day" },
    { id: "claude-haiku-5-5", label: "Claude Haiku 5.5", recommended: false, cost_per_day: "about $0.005 per 3-hour day" },
  ],
};
const without = (n: number, chars = 160_000) =>
  Array.from({ length: n }, (_, i) => ({ day: `2026-10-${String(23 - i).padStart(2, "0")}`, chars, error: null }));

test("money keeps two significant figures, cents below $10", () => {
  expect(money(2.4)).toBe("$2.40");
  expect(money(0.0048)).toBe("$0.0048");
  expect(money(0.2)).toBe("$0.20");
  expect(money(12.34)).toBe("$12");
  expect(money(0)).toBe("$0");
});

test("the range estimate: days, tokens, and the cost scaled from the model's per-day figure", () => {
  // 12 days of 160k characters: 40k tokens each, 480k in all; $0.20 per 40k tokens -> $2.40
  expect(rangeEstimate(without(12), 30, opus))
    .toEqual({ days: 12, text: "12 days, about 480k tokens, about $2.40 with Claude Opus 5.5" });
  // the newest 7 of the days without an insight, as the server picks them
  expect(rangeEstimate(without(12), 7, opus).text).toBe("7 days, about 280k tokens, about $1.40 with Claude Opus 5.5");
  expect(rangeEstimate(without(1, 2_000), 7, opus).text).toBe("1 day, about 500 tokens, about $0.0025 with Claude Opus 5.5");
});

test("the range estimate on this Mac is free, and an endpoint's cost is its own", () => {
  const local = { ...ollama, facts: { ...ollama.facts!, cost: "free, runs on this Mac" } };
  expect(rangeEstimate(without(3), 7, local).text).toBe("3 days, about 120k tokens, free, runs on this Mac");
  expect(rangeEstimate(without(3), 7, ollama).text).toBe("3 days, about 120k tokens, free, runs on this Mac");
  const endpoint = { ...opus, provider: "openai", model: "local-llm", models: [],
    facts: { ...opus.facts, cost: "set by that endpoint" } };
  expect(rangeEstimate(without(2), 7, endpoint).text).toBe("2 days, about 80k tokens, cost set by that endpoint");
});

test("nothing to generate when no day is without an insight", () => {
  expect(rangeEstimate([], 7, opus)).toEqual({ days: 0, text: "Nothing to generate" });
});

test("the range result names how many were generated and each failure", () => {
  expect(rangeResult({ done: 11, errors: [{ day: "2026-10-20", error: "rate limited" }] }))
    .toBe("Generated 11 days; 1 failed: Tuesday, 20 October: rate limited");
  expect(rangeResult({ done: 1, errors: [] })).toBe("Generated 1 day.");
  expect(rangeResult({ done: 0, errors: [{ day: "2026-10-20", error: "a" }, { day: "2026-10-21", error: "b" }] }))
    .toBe("Generated 0 days; 2 failed: Tuesday, 20 October: a; Wednesday, 21 October: b");
});

test("a job the app no longer knows (it restarted) reads as such", () => {
  expect(pollError(new ApiError(404, "not found"))).toBe(VANISHED);
  expect(VANISHED).toBe("The app restarted before this finished. Try again.");
  expect(pollError(new ApiError(400, "No model chosen."))).toBe("No model chosen.");
  expect(pollError(new JobError({ id: "j", kind: "generate", key: "", state: "error", result: null, error: "boom",
    started_ms: 0, finished_ms: 1 }))).toBe("boom");
});
