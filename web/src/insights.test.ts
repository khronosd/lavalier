import { expect, test } from "vitest";
import {
  anthropic, dayState, doneRecord, errorRecord, noProvider, ollama, silentView, view,
} from "./insights.fixtures";
import { followUpHref, generatedLine, generateSentence, NO_SPEECH, tabState } from "./insights";

test("no provider configured comes first, whatever the day holds", () => {
  expect(tabState(dayState(), noProvider, view)).toBe("no-provider");
  expect(tabState(dayState({ state: "done", record: doneRecord }), noProvider, view)).toBe("no-provider");
  expect(tabState(dayState({ reason: "No model chosen." }), ollama, view)).toBe("no-provider");
});

test("a day without a conversation with lines has nothing to summarise", () => {
  expect(tabState(dayState(), ollama, silentView)).toBe("no-speech");
  expect(tabState(dayState({ reason: NO_SPEECH }), ollama, view)).toBe("no-speech");
});

test("none, generating, error and done follow the server's state", () => {
  expect(tabState(dayState(), ollama, view)).toBe("none");
  expect(tabState(dayState({ state: "generating", job: "j1" }), ollama, view)).toBe("generating");
  expect(tabState(dayState({ state: "error", record: errorRecord }), ollama, view)).toBe("error");
  expect(tabState(dayState({ state: "done", record: doneRecord }), ollama, view)).toBe("done");
});

test("a reason Generate is refused makes the day unusable, but a done insight is still shown", () => {
  const reason = "No key saved. Add one in Settings › Model.";
  expect(tabState(dayState({ reason }), anthropic, view)).toBe("unusable");
  expect(tabState(dayState({ state: "error", record: errorRecord, reason }), anthropic, view)).toBe("unusable");
  expect(tabState(dayState({ state: "done", record: doneRecord, reason }), anthropic, view)).toBe("done");
});

test("the Generate sentence names a cloud provider and says a local one stays on this Mac", () => {
  expect(generateSentence(anthropic)).toBe("Sends this day's transcript text to Anthropic.");
  expect(generateSentence(ollama)).toBe("Runs on this Mac.");
});

test("a follow-up with a line links to it; one without has no link", () => {
  const [linked, plain] = doneRecord.insight!.follow_ups;
  expect(followUpHref("2026-10-23", linked)).toBe("#/day/2026-10-23?at=clip_b-0");
  expect(followUpHref("2026-10-23", plain)).toBeNull();
  expect(followUpHref("2026-10-23", { text: "x", at_ms: null, line_id: "a b&c" })).toBe("#/day/2026-10-23?at=a+b%26c");
});

test("the generated line names the model and the time, and says when the day was cut", () => {
  expect(generatedLine(doneRecord)).toBe("Generated by qwen3:8b at 23:05");
  expect(generatedLine({ ...doneRecord, truncated: true }))
    .toBe("Generated by qwen3:8b at 23:05 (the earlier part of the day was left out)");
});
