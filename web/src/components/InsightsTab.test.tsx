test("Ask: Enter sends the question, Thinking… while it runs, then the answer; a second question replaces it", async () => {
  days = [dayState({ state: "done", record: doneRecord })];
  jobs = [job({ kind: "ask" }), job({ kind: "ask", state: "done", result: { answer: "You tested the pendant." } })];
  const { container } = await show();
  const input = screen.getByRole("textbox", { name: "Ask about this day" }) as HTMLInputElement;
  fireEvent.input(input, { target: { value: "what happened?" } });
  fireEvent.submit(input.form!);
  await flush();
  expect(calls.find((c) => c.key === "POST /api/ask")!.body).toEqual({ day: DAY, question: "what happened?" });
  expect(screen.getByText("Thinking…")).toBeTruthy();

  await tick();
  const answer = screen.getByText("You tested the pendant.");
  expect(answer.classList.contains("reading")).toBe(true);
  expect(screen.queryByText("Thinking…")).toBeNull();
  expect(input.value).toBe("what happened?");

  jobs = [job({ kind: "ask", state: "done", result: { answer: "Ana and Ben." } })];
  fireEvent.input(input, { target: { value: "who was there?" } });
  fireEvent.submit(input.form!);
  await flush();
  await flush();
  expect(screen.getByText("Ana and Ben.")).toBeTruthy();
  expect(screen.queryByText("You tested the pendant.")).toBeNull();
  expect(container.querySelectorAll(".ask-answer")).toHaveLength(1);
});

