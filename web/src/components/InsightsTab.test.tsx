test("none: Generate now with the cloud sentence; it posts, polls every second, then shows the day", async () => {
  facts = anthropic;
  days = [dayState(), dayState({ state: "done", record: doneRecord })];
  jobs = [job(), job(), job({ state: "done", result: { record: doneRecord, stored: true } })];
  await show();
  expect(screen.getByText("Sends this day's transcript text to Anthropic.")).toBeTruthy();

  fireEvent.click(screen.getByRole("button", { name: "Generate now" }));
  await flush();
  expect(calls.filter((c) => c.key.startsWith("POST")).map((c) => c.key)).toEqual([`POST /api/insights/generate/${DAY}`]);
  expect(screen.getByText("Generating with claude-haiku…")).toBeTruthy();
  expect(screen.queryByRole("button", { name: "Generate now" })).toBeNull();
  expect(count("GET /api/jobs/j1")).toBe(1);

  await tick();
  expect(count("GET /api/jobs/j1")).toBe(2);
  expect(count(`GET /api/insights/${DAY}`)).toBe(1);
  await tick();
  expect(count("GET /api/jobs/j1")).toBe(3);
  expect(count(`GET /api/insights/${DAY}`)).toBe(2); // fetched again once the job was done
  expect(screen.getByText("A short pendant test late in the evening.")).toBeTruthy();
  expect(screen.queryByText(/Generating/)).toBeNull();

  await tick(5000);
  expect(count("GET /api/jobs/j1")).toBe(3); // no more polling
});

