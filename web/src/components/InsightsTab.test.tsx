import { act, cleanup, fireEvent, render, screen } from "@testing-library/preact";
import { afterEach, beforeEach, expect, test, vi } from "vitest";
import type { InsightDayState, Job, ProviderFacts } from "../api";
import {
  anthropic, dayState, doneRecord, errorRecord, job, noProvider, ollama, silentView, view,
} from "../insights.fixtures";
import { InsightsTab, MODEL_PRIVACY } from "./InsightsTab";

const DAY = "2026-10-23";
const json = (body: unknown, status = 200) =>
  new Response(JSON.stringify(body), { status, headers: { "Content-Type": "application/json" } });

let calls: { key: string; body: unknown }[];
let facts: ProviderFacts;
let days: InsightDayState[]; // one per GET of the day's insights; the last one repeats
let jobs: Job[];             // one per GET of a job; the last one repeats
let post: (key: string, body: unknown) => Response;

beforeEach(() => {
  vi.useFakeTimers();
  calls = [];
  facts = ollama;
  days = [dayState()];
  jobs = [job()];
  post = () => json({ job: "j1" }, 202);
  vi.stubGlobal("fetch", vi.fn(async (url: string, init?: RequestInit) => {
    const key = `${init?.method ?? "GET"} ${url}`;
    const body = init?.body ? JSON.parse(init.body as string) : undefined;
    calls.push({ key, body });
    if (key === "GET /api/insights/providers") return json(facts);
    if (key === `GET /api/insights/${DAY}`) return json(days.length > 1 ? days.shift() : days[0]);
    if (key === "GET /api/jobs/j1") return json(jobs.length > 1 ? jobs.shift() : jobs[0]);
    if (key.startsWith("POST ")) return post(key, body);
    throw new Error(`unexpected ${key}`);
  }));
});
afterEach(() => {
  cleanup();
  vi.useRealTimers();
  vi.unstubAllGlobals();
});

const flush = () => act(async () => { await vi.advanceTimersByTimeAsync(0); });
const tick = (ms = 1000) => act(async () => { await vi.advanceTimersByTimeAsync(ms); });
const count = (key: string) => calls.filter((c) => c.key === key).length;

async function show(v = view) {
  const r = render(<InsightsTab day={DAY} view={v} />);
  await flush();
  return r;
}

test("done: the summary in the reading face, follow-ups on the margin grid, people, topics and the truncated note", async () => {
  days = [dayState({ state: "done", record: { ...doneRecord, truncated: true } })];
  const { container } = await show();

  const summary = screen.getByText("A short pendant test late in the evening.");
  expect(summary.classList.contains("reading")).toBe(true);

  expect(screen.getByRole("heading", { name: "Follow-ups" })).toBeTruthy();
  const rows = [...container.querySelectorAll(".follow-ups .line")];
  expect(rows.map((r) => r.textContent)).toEqual([
    "22:56:09Check the mute survives a reboot", "23:04:00Plug the pendant in before the sync"]);
  const link = rows[0].querySelector("a.time")!;
  expect(link.getAttribute("href")).toBe("#/day/2026-10-23?at=clip_b-0");
  expect(rows[1].querySelector("a")).toBeNull();
  expect(rows[1].querySelector("time.time")!.textContent).toBe("23:04:00");

  expect(screen.getByRole("heading", { name: "People" }).nextElementSibling!.textContent).toBe("Ana, Ben");
  expect(screen.getByRole("heading", { name: "Topics" }).nextElementSibling!.textContent).toBe("pendant firmware, bluetooth");
  expect(screen.getByText("Generated by qwen3:8b at 23:05 (the earlier part of the day was left out)")).toBeTruthy();
  expect(screen.getByRole("button", { name: "Regenerate" })).toBeTruthy();
  expect(screen.getByText("Runs on this Mac.")).toBeTruthy();
  expect(screen.getByRole("textbox", { name: "Ask about this day" })).toBeTruthy();
  expect(container.querySelector("[style]")).toBeNull();
});

